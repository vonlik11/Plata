# ── Генерация датасета ─────────────────────────────────────────────────

def generate_request_text(scenario: str, base_prompt: str) -> str:
    """Генерирует расширенный текст запроса с контекстом."""
    context_parts = [
        base_prompt,
        f"\n\nКонтекст: Работаю над проектом в сфере IT, команда из 10 человек.",
        f"Срочность: {'высокая' if random.random() > 0.7 else 'средняя'}.",
        f"Дополнительные требования: стиль — деловой, объём — {'кратко' if random.random() > 0.5 else 'подробно'}.",
    ]
    # Имитация длинных запросов (ближе к 100k токенов)
    filler = " ".join([base_prompt] * random.randint(3, 8))
    return " ".join(context_parts) + "\n\n" + filler


def generate_dataset(n_rows: int = 500, output_path: str = "data/logs.csv"):
    """Генерирует CSV-файл с логами запросов."""
    import os
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    rows = []
    start_date = datetime(2024, 1, 1)

    for _ in range(n_rows):
        category = random.choice(list(CATEGORIES.keys()))
        scenario_name = random.choice(list(CATEGORIES[category]["scenarios"].keys()))
        base_prompt = random.choice(CATEGORIES[category]["scenarios"][scenario_name])
        request_text = generate_request_text(scenario_name, base_prompt)

        # Метаданные
        user_id = f"user_{random.randint(1, 50):03d}"
        timestamp = start_date + timedelta(
            days=random.randint(0, 180),
            hours=random.randint(0, 23),
            minutes=random.randint(0, 59),
        )
        tokens = random.randint(50_000, 150_000)  # среднее ~100k
        response_time = random.uniform(2.0, 45.0)  # секунды
        satisfaction = random.choice([None, 1, 2, 3, 4, 5])  # не всегда заполнено

        rows.append({
            "id": str(uuid.uuid4())[:8],
            "timestamp": timestamp.isoformat(),
            "user_id": user_id,
            "request_text": request_text,
            "true_category": category,
            "true_scenario": scenario_name,
            "token_count": tokens,
            "response_time_sec": round(response_time, 2),
            "satisfaction_score": satisfaction if satisfaction else "",
        })

    # Сортируем по времени
    rows.sort(key=lambda r: r["timestamp"])

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)

    print(f"Сгенерировано {n_rows} записей → {output_path}")
    return output_path


if __name__ == "__main__":
    generate_dataset(n_rows=500)
